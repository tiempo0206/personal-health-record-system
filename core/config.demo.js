(function (PHR) {
  'use strict';

  PHR.config = PHR.config || {};

  /**
   * 测试专用：万能短信验证码。
   * 打开后，任意账号在第二因素环节输入 universalSmsCode 都能通过，
   * 用于测试时免去"每次查看短信"的麻烦。
   *
   * 使用万能码时系统会**照常写入审计日志**，并在 detail 中明确标注
   * 「使用了测试用万能验证码」——也就是说它不会被悄悄用掉，
   * 在「访问追踪」里一眼就能看出来。
   */
  PHR.config.demo = {
    allowUniversalSmsCode: true,  // 是否启用万能验证码（仅测试环境允许为 true）
    universalSmsCode: '000000'    // 万能验证码本身
  };

})(window.PHR);
